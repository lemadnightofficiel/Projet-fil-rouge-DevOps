mariadb -u root -p"$MYSQL_ROOT_PASSWORD"<<EOSQL

CREATE DATABASE IF NOT EXISTS ${MYSQL_DATABASENAME}
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_general_ci;

CREATE USER IF NOT EXISTS '$MYSQL_USERNAME'@'%' IDENTIFIED BY '${MYSQL_USER_PASSWORD}';
GRANT INSERT, SELECT, UPDATE, DELETE ON ${MYSQL_DATABASENAME}.* TO '${MYSQL_USERNAME}'@'%';

USE ${MYSQL_DATABASENAME};

CREATE TABLE WeatherForecasts (
    idWeather VARCHAR(255) NOT NULL PRIMARY KEY,
    Date DATETIME NOT NULL,
    Town VARCHAR(255) NOT NULL,
    PostalCode VARCHAR(5) NOT NULL,
    TemperatureC INTEGER NOT NULL,
    Summary VARCHAR(255)
);

EOSQL

echo "[Init] Base et table créées avec succès"